-- Makes signed waivers a protected legal record.
-- Run once in the Supabase SQL Editor (it is safe to re-run).
--
-- After this runs:
--  * The server sets signed_at and records which staff login collected the signature.
--  * Signed fields (names, signatures, signed time, waiver text) cannot be edited by app users.
--  * Waivers cannot be deleted by app users. Deleting or correcting a record requires the SQL Editor.
--  * Contact detail edits are allowed, and every change is kept in waiver_contact_history.
--  * The exact waiver wording and its SHA-256 hash are stored with each signature.
--  * A PDF copy of each signed waiver is kept in the private "signed-waivers" bucket.

alter table public.waivers
  add column if not exists waiver_text text,
  add column if not exists waiver_text_sha256 text,
  add column if not exists signer_relationship text not null default '',
  add column if not exists signed_by uuid references auth.users(id) on delete set null,
  add column if not exists signed_by_email text,
  add column if not exists signed_user_agent text,
  add column if not exists pdf_path text,
  add column if not exists pdf_sha256 text;

create table if not exists public.waiver_contact_history (
  id bigint generated by default as identity primary key,
  waiver_id uuid not null references public.waivers(id) on delete restrict,
  changed_at timestamptz not null default now(),
  changed_by uuid,
  changed_by_email text,
  previous jsonb not null,
  updated jsonb not null
);

alter table public.waiver_contact_history enable row level security;

drop policy if exists waiver_contact_history_select_staff on public.waiver_contact_history;
create policy waiver_contact_history_select_staff on public.waiver_contact_history
  for select to authenticated
  using (public.current_user_role() is not null);

-- Replace the old "all actions" policy with select/insert/update only (no delete).
drop policy if exists waivers_all_staff on public.waivers;
drop policy if exists waivers_select_staff on public.waivers;
drop policy if exists waivers_insert_staff on public.waivers;
drop policy if exists waivers_update_staff on public.waivers;
create policy waivers_select_staff on public.waivers
  for select to authenticated using (public.current_user_role() is not null);
create policy waivers_insert_staff on public.waivers
  for insert to authenticated with check (public.current_user_role() is not null);
create policy waivers_update_staff on public.waivers
  for update to authenticated
  using (public.current_user_role() is not null)
  with check (public.current_user_role() is not null);

-- Server-controlled fields on insert.
create or replace function public.waivers_before_insert()
returns trigger language plpgsql as $$
begin
  if auth.uid() is not null then
    new.signed_at := now();
    new.created_at := now();
    new.updated_at := now();
    new.signed_by := auth.uid();
    new.signed_by_email := auth.jwt() ->> 'email';
  end if;
  return new;
end;
$$;

drop trigger if exists waivers_before_insert on public.waivers;
create trigger waivers_before_insert before insert on public.waivers
  for each row execute function public.waivers_before_insert();

-- Lock signed fields and log contact changes. The SQL Editor (no signed-in app user) is exempt.
create or replace function public.waivers_before_update()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null then
    if new.student_id is distinct from old.student_id
      or new.waiver_version is distinct from old.waiver_version
      or new.participant_name is distinct from old.participant_name
      or new.parent_guardian_name is distinct from old.parent_guardian_name
      or new.signer_relationship is distinct from old.signer_relationship
      or new.signature is distinct from old.signature
      or new.snapshot is distinct from old.snapshot
      or new.signed_at is distinct from old.signed_at
      or new.created_at is distinct from old.created_at
      or new.waiver_text is distinct from old.waiver_text
      or new.waiver_text_sha256 is distinct from old.waiver_text_sha256
      or new.signed_by is distinct from old.signed_by
      or new.signed_by_email is distinct from old.signed_by_email
      or new.signed_user_agent is distinct from old.signed_user_agent
      or new.legacy_key is distinct from old.legacy_key
      or (old.pdf_path is not null and new.pdf_path is distinct from old.pdf_path)
      or (old.pdf_sha256 is not null and new.pdf_sha256 is distinct from old.pdf_sha256)
    then
      raise exception 'Signed waiver fields cannot be changed';
    end if;
  end if;

  if new.phone is distinct from old.phone
    or new.email is distinct from old.email
    or new.emergency_name is distinct from old.emergency_name
    or new.emergency_phone is distinct from old.emergency_phone
    or new.emergency_relationship is distinct from old.emergency_relationship
    or new.date_of_birth is distinct from old.date_of_birth
  then
    insert into public.waiver_contact_history (waiver_id, changed_by, changed_by_email, previous, updated)
    values (
      old.id, auth.uid(), auth.jwt() ->> 'email',
      jsonb_build_object('phone', old.phone, 'email', old.email, 'emergency_name', old.emergency_name, 'emergency_phone', old.emergency_phone, 'emergency_relationship', old.emergency_relationship, 'date_of_birth', old.date_of_birth),
      jsonb_build_object('phone', new.phone, 'email', new.email, 'emergency_name', new.emergency_name, 'emergency_phone', new.emergency_phone, 'emergency_relationship', new.emergency_relationship, 'date_of_birth', new.date_of_birth)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists waivers_before_update on public.waivers;
create trigger waivers_before_update before update on public.waivers
  for each row execute function public.waivers_before_update();

create or replace function public.waivers_before_delete()
returns trigger language plpgsql as $$
begin
  if auth.uid() is not null then
    raise exception 'Signed waivers cannot be deleted from the app';
  end if;
  return old;
end;
$$;

drop trigger if exists waivers_before_delete on public.waivers;
create trigger waivers_before_delete before delete on public.waivers
  for each row execute function public.waivers_before_delete();

-- Private storage for PDF copies. Staff can add and read files, never replace or delete them.
insert into storage.buckets (id, name, public)
values ('signed-waivers', 'signed-waivers', false)
on conflict (id) do nothing;

drop policy if exists signed_waivers_select_staff on storage.objects;
drop policy if exists signed_waivers_insert_staff on storage.objects;
create policy signed_waivers_select_staff on storage.objects
  for select to authenticated
  using (bucket_id = 'signed-waivers' and public.current_user_role() is not null);
create policy signed_waivers_insert_staff on storage.objects
  for insert to authenticated
  with check (bucket_id = 'signed-waivers' and public.current_user_role() is not null);
